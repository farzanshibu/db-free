// WHAT:  Copies a table: its structure, optionally its rows, optionally its indexes.
// WHY:   "Duplicate table" is the safe way to experiment on real data. A copy made
//        from the structure the form read (`describe`) behaves the same on every
//        dialect, where `CREATE TABLE … AS SELECT` would lose keys and defaults
//        and `LIKE` exists on only two engines.
// HOW:   The target is the source's `TableSpec` with identities cleared (no
//        original names, generated constraint names) and any self-reference
//        pointed at the copy. Rows follow as one INSERT … SELECT; afterwards the
//        counters of auto-increment columns are moved past the copied values on
//        the engines where an explicit insert does not do it itself.
// WHERE: src-tauri/src/integrations/ddl/create.rs (build_create)

fn same_table(a: &TableRef, b: &TableRef) -> bool {
    let schema = |t: &TableRef| t.schema.clone().filter(|s| !s.is_empty()).unwrap_or_default();
    same_name(&schema(a), &schema(b)) && same_name(&a.name, &b.name)
}

/// `<target>_<what the source index was called after its table>`.
fn index_name(source: &str, target: &str, index: &str) -> String {
    let rest = index.strip_prefix(&format!("{source}_")).unwrap_or(index);
    derived_name(&[target, rest])
}

pub fn duplicate_table(cx: &Cx, spec: &DuplicateSpec, source: &TableSpec) -> AppResult<Vec<String>> {
    if cx.dialect == Dialect::Mongo {
        return mongo::duplicate(spec);
    }
    if !support_of(cx.dialect).duplicate_table {
        return Err(cx.cannot("copy a table (it has no INSERT … SELECT)"));
    }
    check_name("table", &spec.target.name)?;
    // The copy lands beside its source unless the form named another schema.
    let target = TableRef { schema: spec.target.schema.clone().filter(|s| !s.is_empty()).or_else(|| spec.source.schema.clone()), name: spec.target.name.clone() };
    if same_table(&spec.source, &target) {
        return Err(AppError::invalid_input("Pick a different name for the copy."));
    }

    let mut shape = source.clone();
    shape.table = target.clone();
    shape.if_not_exists = false;
    shape.primary_key_name = None;
    for column in &mut shape.columns {
        column.original_name = None;
        column.unique_name = None;
    }
    for fk in &mut shape.foreign_keys {
        fk.original_name = None;
        fk.name = None;
        if same_table(&fk.ref_table, &spec.source) {
            fk.ref_table = target.clone();
        }
    }
    shape.indexes = if spec.include_indexes {
        source.indexes.iter().map(|i| IndexSpec { name: index_name(&spec.source.name, &target.name, &i.name), ..i.clone() }).collect()
    } else {
        Vec::new()
    };

    let created = build_create(cx, &shape)?;
    let mut out = created.prelude;
    out.push(created.table);
    if spec.include_data {
        out.extend(copy_rows(cx, spec, &target, source)?);
    }
    out.extend(created.indexes);
    Ok(out)
}

fn copy_rows(cx: &Cx, spec: &DuplicateSpec, target: &TableRef, source: &TableSpec) -> AppResult<Vec<String>> {
    let names: Vec<String> = source.columns.iter().map(|c| c.name.clone()).collect();
    let list = cx.columns(&names);
    let insert = format!("INSERT INTO {} ({list}) SELECT {list} FROM {}", cx.table(target), cx.table(&spec.source));
    let auto: Vec<&str> = source.columns.iter().filter(|c| c.auto_increment).map(|c| c.name.as_str()).collect();
    let mut out = Vec::new();
    match cx.dialect {
        Dialect::Mssql if !auto.is_empty() => {
            out.push(format!("SET IDENTITY_INSERT {} ON", cx.table(target)));
            out.push(insert);
            out.push(format!("SET IDENTITY_INSERT {} OFF", cx.table(target)));
        }
        Dialect::Postgres => {
            out.push(insert);
            // An explicit insert leaves a serial's sequence at 1; move it past the copied ids.
            for column in &auto {
                out.push(format!(
                    "SELECT setval(pg_get_serial_sequence({}, {}), COALESCE(MAX({}), 0) + 1, false) FROM {}",
                    cx.lit(&cx.table(target)),
                    cx.lit(column),
                    cx.q(column),
                    cx.table(target)
                ));
            }
        }
        Dialect::Oracle => {
            out.push(insert);
            for column in &auto {
                out.push(format!("ALTER TABLE {} MODIFY ({} GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE))", cx.table(target), cx.q(column)));
            }
        }
        Dialect::Duckdb => {
            out.push(insert);
            // DuckDB has no setval: draw one value per copied id so the sequence ends past them.
            for column in &auto {
                let sequence = cx.table(&duckdb_sequence(target, column));
                out.push(format!(
                    "SELECT count(nextval({})) FROM range(COALESCE((SELECT MAX({}) FROM {}), 0))",
                    cx.lit(&sequence),
                    cx.q(column),
                    cx.table(target)
                ));
            }
        }
        _ => out.push(insert),
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::integrations::ddl::alter::tests::live;
    use crate::integrations::ddl::create::tests::{fk, pk, spec, table};
    use crate::integrations::ddl::types::tests::col;
    use crate::model::{ColumnDefault, Engine};

    fn source(int: &str, text: &str) -> TableSpec {
        let mut id = pk("id", int);
        id.auto_increment = true;
        let mut name = col("name", text);
        name.nullable = false;
        name.unique = true;
        name.unique_name = Some("people_name_key".into());
        let mut at = col("at", "timestamp");
        at.default = ColumnDefault::Now;
        let mut t = spec(table("people"), vec![id, name, at]);
        t.primary_key_name = Some("people_pkey".into());
        t.indexes = vec![IndexSpec { name: "people_at_idx".into(), columns: vec!["at".into()], unique: false }];
        let mut owner = fk(&["id"], "people", &["id"]);
        owner.name = Some("people_self_fkey".into());
        t.foreign_keys = vec![owner];
        live(t)
    }

    fn duplicate(engine: Engine, source: &TableSpec, data: bool, indexes: bool) -> Vec<String> {
        let spec = DuplicateSpec { source: table("people"), target: table("people_copy"), include_data: data, include_indexes: indexes };
        super::super::duplicate_table(engine, &spec, source).unwrap_or_else(|e| vec![format!("ERR {e}")])
    }

    #[test]
    fn postgres_copy_with_data_and_indexes() {
        let statements = duplicate(Engine::Postgres, &source("integer", "varchar"), true, true);
        assert_eq!(
            statements,
            vec![
                "CREATE TABLE \"people_copy\" (\n  \"id\" serial,\n  \"name\" varchar NOT NULL UNIQUE,\n  \"at\" timestamp DEFAULT now(),\n  PRIMARY KEY (\"id\"),\n  CONSTRAINT \"people_copy_id_fkey\" FOREIGN KEY (\"id\") REFERENCES \"people_copy\" (\"id\")\n)",
                "INSERT INTO \"people_copy\" (\"id\", \"name\", \"at\") SELECT \"id\", \"name\", \"at\" FROM \"people\"",
                "SELECT setval(pg_get_serial_sequence('\"people_copy\"', 'id'), COALESCE(MAX(\"id\"), 0) + 1, false) FROM \"people_copy\"",
                "CREATE INDEX \"people_copy_at_idx\" ON \"people_copy\" (\"at\")",
            ]
        );
    }

    #[test]
    fn structure_only_copies_neither_rows_nor_indexes() {
        let statements = duplicate(Engine::Postgres, &source("integer", "varchar"), false, false);
        assert_eq!(statements.len(), 1);
        assert!(statements[0].starts_with("CREATE TABLE \"people_copy\""));
    }

    #[test]
    fn each_engine_advances_its_counters_its_own_way() {
        let mssql = duplicate(Engine::Mssql, &source("int", "varchar"), true, false);
        assert_eq!(mssql[1], "SET IDENTITY_INSERT [people_copy] ON");
        assert_eq!(mssql[2], "INSERT INTO [people_copy] ([id], [name], [at]) SELECT [id], [name], [at] FROM [people]");
        assert_eq!(mssql[3], "SET IDENTITY_INSERT [people_copy] OFF");
        let oracle = duplicate(Engine::Oracle, &source("NUMBER", "VARCHAR2"), true, false);
        assert_eq!(oracle.last().map(String::as_str), Some("ALTER TABLE \"people_copy\" MODIFY (\"id\" GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE))"));
        let duck = duplicate(Engine::Duckdb, &source("INTEGER", "VARCHAR"), true, false);
        assert_eq!(duck[0], "CREATE SEQUENCE \"people_copy_id_seq\"");
        assert_eq!(duck.last().map(String::as_str), Some("SELECT count(nextval('\"people_copy_id_seq\"')) FROM range(COALESCE((SELECT MAX(\"id\") FROM \"people_copy\"), 0))"));
        let mysql = duplicate(Engine::Mysql, &source("int", "varchar"), true, true);
        assert_eq!(mysql.len(), 3, "MySQL needs no counter fix-up: {mysql:#?}");
        assert!(mysql[1].starts_with("INSERT INTO `people_copy`"));
        assert!(mysql[2].starts_with("CREATE INDEX `people_copy_at_idx` ON `people_copy`"));
    }

    #[test]
    fn the_copy_must_differ_from_the_source_and_engines_without_insert_select_refuse() {
        let spec = DuplicateSpec { source: table("people"), target: table("PEOPLE"), include_data: false, include_indexes: false };
        let same = super::super::duplicate_table(Engine::Postgres, &spec, &source("integer", "varchar")).err().map(|e| e.to_string());
        assert_eq!(same.as_deref(), Some("Pick a different name for the copy."));
        let cassandra = duplicate(Engine::Cassandra, &source("int", "text"), false, false);
        assert!(cassandra[0].starts_with("ERR Cassandra cannot copy a table"), "{}", cassandra[0]);
        // The copy keeps the source's schema unless told otherwise.
        let mut qualified = source("integer", "varchar");
        qualified.table.schema = Some("app".into());
        let spec = DuplicateSpec {
            source: TableRef { schema: Some("app".into()), name: "people".into() },
            target: table("people_copy"),
            include_data: true,
            include_indexes: false,
        };
        let out = super::super::duplicate_table(Engine::Postgres, &spec, &qualified).unwrap_or_default();
        assert!(out[1].starts_with("INSERT INTO \"app\".\"people_copy\" (") && out[1].ends_with("FROM \"app\".\"people\""), "{}", out[1]);
    }

    #[test]
    fn mongo_copies_documents_with_out() {
        let spec = DuplicateSpec {
            source: TableRef { schema: Some("shop".into()), name: "orders".into() },
            target: TableRef { schema: Some("shop".into()), name: "orders_copy".into() },
            include_data: true,
            include_indexes: true,
        };
        let out = super::super::duplicate_table(Engine::Mongodb, &spec, &spec_of_collection()).unwrap_or_default();
        assert_eq!(out, vec![r#"{"aggregate":"orders","pipeline":[{"$out":"orders_copy"}],"cursor":{},"$db":"shop"}"#.to_string()]);
    }

    fn spec_of_collection() -> TableSpec {
        spec(TableRef { schema: Some("shop".into()), name: "orders".into() }, Vec::new())
    }
}
